/**
 * Domain error carrying a stable code. Every service throws this shape so
 * the error handler can render the spec 09 §7 envelope deterministically.
 */
export class DomainError extends Error {
  /**
   * @param {string} code one of ERROR_CODES
   * @param {string} [message] human-readable message
   * @param {object} [opts]
   * @param {boolean} [opts.retryable=false]
   * @param {object|null} [opts.details=null]
   * @param {number} [opts.status] override HTTP status
   */
  constructor(code, message, opts = {}) {
    super(message || code)
    this.name = 'DomainError'
    this.code = code
    this.retryable = opts.retryable ?? false
    this.details = opts.details ?? null
    this.statusCode = opts.status ?? STATUS_BY_CODE[code] ?? HTTP_STATUS.BAD_REQUEST
  }
}
